def _theme(css_vars: dict[str, str]) -> Theme:
    return Theme(id="t", display_name="T", qt_palette={}, css_vars=css_vars)


def test_build_reference_writes_a_real_docx(tmp_path: Path):
    theme = _theme({
        "font-family-text": "Calibri, sans-serif",
        "font-family-headings": "Georgia, serif",
        "fg": "#111111", "heading-color": "#003366",
        "h1-size": "28pt", "h1-weight": "700",
    })
    target = tmp_path / "corporate.docx"
    mr.build_reference(theme, target)
    assert target.is_file()
    assert target.stat().st_size > 1_000

    doc = Document(str(target))
    assert doc.styles["Normal"].font.name == "Calibri"
    assert doc.styles["Heading 1"].font.name == "Georgia"
    assert doc.styles["Heading 1"].font.bold is True


def test_build_reference_applies_page_geometry(tmp_path: Path):
    from docx.shared import Inches

    target = tmp_path / "geom.docx"
    mr.build_reference(_theme({}), target)
    doc = Document(str(target))
    section = doc.sections[0]
    assert section.page_width == Inches(8.5)
    assert section.page_height == Inches(11)
    assert section.top_margin == Inches(1)


def test_build_reference_defaults_when_css_vars_are_empty(tmp_path: Path):
    """An empty theme (no css_vars) still produces a valid, styled docx."""
    target = tmp_path / "bare.docx"
    mr.build_reference(_theme({}), target)
    doc = Document(str(target))
    assert doc.styles["Normal"].font.name == "Calibri"


def test_build_reference_heading_color_falls_back_to_fg(tmp_path: Path):
    """No heading-color: headings use the body text colour."""
    target = tmp_path / "fallback.docx"
    mr.build_reference(_theme({"fg": "#204060"}), target)
    doc = Document(str(target))
    assert doc.styles["Heading 1"].font.color.rgb == RGBColor.from_string(
        "204060"
    )


# --- Missing built-in styles: defensive KeyError branches --------------


class _HidingStyles:
    """Wraps a real Styles collection, hiding a chosen set of names.

    Simulates a Document template (a different Word/Pandoc default) that
    lacks one of the "nice to have" styles build_reference re-skins --
    proving the try/except KeyError guards actually degrade gracefully
    instead of crashing, since python-docx's OWN default template always
    ships every style this module touches.
    """

    def __init__(self, real_styles, hidden: set[str]) -> None:
        self._real = real_styles
        self._hidden = hidden

    def __getitem__(self, name: str):
        if name in self._hidden:
            raise KeyError(name)
        return self._real[name]


class _HidingDocument:
    """A python-docx Document with some styles hidden from lookup."""

    def __init__(self, hidden: set[str]) -> None:
        self._real = Document()
        self.sections = self._real.sections
        self.styles = _HidingStyles(self._real.styles, hidden)

    def save(self, path) -> None:
        self._real.save(path)


@pytest.mark.parametrize(
    "hidden",
    [
        {"Body Text", "No Spacing"},
        {"Title", "Subtitle"},
        {"Caption"},
        {"Quote", "Intense Quote"},
    ],
)
def test_build_reference_skips_missing_optional_styles(
    tmp_path, monkeypatch, hidden
):
    """A template missing an optional style is skipped, not fatal."""
    monkeypatch.setattr(mr, "Document", lambda: _HidingDocument(hidden))
    target = tmp_path / "missing_styles.docx"
    mr.build_reference(_theme({}), target)  # must not raise
    assert target.is_file()


