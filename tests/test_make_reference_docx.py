def test_main_writes_one_docx_per_bundled_theme(tmp_path, monkeypatch):
    from epy_reports._core import themes

    monkeypatch.setattr(mr, "OUT_DIR", tmp_path)
    # main() logs each path via target.relative_to(ROOT); ROOT must be an
    # ancestor of the redirected OUT_DIR for that call to succeed.
    monkeypatch.setattr(mr, "ROOT", tmp_path)
    exit_code = mr.main()
    assert exit_code == 0
    for theme_id in themes.THEMES:
        assert (tmp_path / f"{theme_id}.docx").is_file()
