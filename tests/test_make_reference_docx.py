def test_first_font_extracts_first_family():
    assert mr._first_font('"Calibri", Arial, sans-serif', "X") == "Calibri"


def test_first_font_empty_uses_default():
    assert mr._first_font("", "Georgia") == "Georgia"


def test_pt_parses_a_pt_suffixed_size():
    assert mr._pt("14pt", 11.0) == 14.0


def test_pt_parses_a_bare_number():
    assert mr._pt("14", 11.0) == 14.0


def test_pt_invalid_uses_default():
    assert mr._pt("not-a-size", 11.0) == 11.0


def test_pt_empty_uses_default():
    assert mr._pt("", 11.0) == 11.0


def test_bold_keyword_values():
    assert mr._bold("bold")
    assert mr._bold("bolder")


def test_bold_numeric_weight_threshold():
    assert mr._bold("600")
    assert mr._bold("700")
    assert not mr._bold("400")


def test_bold_invalid_weight_is_false():
    assert not mr._bold("not-a-weight")


def test_rgb_parses_hex_color():
    assert mr._rgb("#FF0010") == RGBColor.from_string("FF0010")


def test_rgb_wrong_length_uses_default():
    assert mr._rgb("#ABC", "112233") == RGBColor.from_string("112233")


def test_rgb_non_hex_characters_use_default():
    """Six characters that are not valid hex digits fall back to default.

    Exercises the ``except ValueError`` branch in ``_rgb``: the length
    check alone (``len(text) != 6``) lets a 6-character non-hex string
    (e.g. from a malformed theme file) through to ``RGBColor.from_string``,
    which is what actually raises.
    """
    assert mr._rgb("#GGGGGG", "445566") == RGBColor.from_string("445566")


def test_rgb_empty_uses_black_default():
    assert mr._rgb("") == RGBColor.from_string("000000")


