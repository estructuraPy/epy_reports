"""Tests for the per-theme Word reference-doc generator (dev/build tool).

Like ``make_icon``, this script is never imported by the shipping
application (0% coverage before this file existed). It is pure
python-docx -- no Qt -- so it is tested directly. ``main()`` writes into
a hardcoded ``OUT_DIR`` under the real bundled
``_config/_assets/reference_docx``; every test that calls it redirects
``OUT_DIR`` to ``tmp_path`` first so the real, git-tracked .docx files
bundled with the app are never touched or regenerated by a test run.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from docx import Document
from docx.shared import RGBColor

from epy_reports._core._packaging import make_reference_docx as mr
from epy_reports._core.themes_base import Theme

# ---------------------------------------------------------------------------
# Pure helpers
